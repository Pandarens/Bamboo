//! Журнал действий и откат (ТЗ, раздел 12).
//!
//! Главный принцип проекта: ни одно действие не выполняется без записи
//! обратного рецепта в журнал. Порядок строгий — сначала запись, потом
//! действие, потом подтверждение. При падении между записью и подтверждением
//! следующий запуск найдёт незакрытую запись и разберётся с ней.
//!
//! Журнал живёт в отдельном файле от базы телеметрии: потерять историю
//! метрик неприятно, потерять возможность откатить изменения — недопустимо.

#![forbid(unsafe_code)]

pub mod entry;
pub mod journal;
pub mod watchdog;

pub use entry::{Actor, Entry, Status, Target};
pub use journal::{Journal, NewEntry};
pub use watchdog::{should_revert, Baseline, Observed, RevertReason, WINDOW_MS};
