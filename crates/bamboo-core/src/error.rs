//! Ошибки.

use core::fmt;

pub type Result<T> = core::result::Result<T, Error>;

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Error {
    /// Вызов NT API вернул неуспешный `NTSTATUS`.
    Nt { call: &'static str, status: i32 },
    /// Вызов Win32 API не удался, код из `GetLastError`.
    Win32 { call: &'static str, code: u32 },
    /// Возможность недоступна на этой версии Windows или в этой конфигурации.
    ///
    /// Отдельный вариант, а не общая ошибка: по ТЗ при невозможности прочитать
    /// данные (например, SMART через RAID-контроллер) полагается честно сказать
    /// «не могу», а не показывать оценку.
    Unsupported(&'static str),
    /// Данные от системы не соответствуют ожидаемой структуре.
    Malformed(&'static str),
}

/// Человеческое объяснение частых кодов ошибок Windows.
///
/// Голый номер вроде «ошибка 5» пользователю не говорит ничего, а именно
/// эти несколько кодов он и увидит: попытка тронуть чужой процесс, процесс
/// закрылся между запросом и действием, возможности нет на этой версии.
/// Остальные коды оставляем числом — выдумывать расшифровку хуже, чем
/// честно показать номер.
fn win32_meaning(code: u32) -> Option<&'static str> {
    Some(match code {
        2 => "система не нашла указанный объект",
        5 => "отказано в доступе: у Bamboo не хватает прав на этот процесс.               Так бывает с процессами, запущенными от администратора,               и с защищёнными процессами Windows",
        50 => "Windows не поддерживает эту возможность здесь. Ограничение               скорости диска работает не на всякой сборке и не на всяком               томе — например, его нет у динамических дисков и у томов               не на NTFS. Отказ пришёл от системы, обойти его нечем",
        87 => "система не приняла параметры вызова",
        1168 => "объект не найден: скорее всего, процесс уже завершился",
        1314 => "не хватает привилегии для этой операции",
        _ => return None,
    })
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Error::Nt { call, status } => {
                write!(f, "{call} вернул NTSTATUS 0x{:08X}", *status as u32)
            }
            Error::Win32 { call, code } => match win32_meaning(*code) {
                Some(meaning) => write!(f, "{call}: {meaning} (код {code})"),
                None => write!(f, "{call} завершился с ошибкой {code}"),
            },
            Error::Unsupported(what) => write!(f, "недоступно в этой конфигурации: {what}"),
            Error::Malformed(what) => write!(f, "неожиданный формат данных: {what}"),
        }
    }
}

impl std::error::Error for Error {}
