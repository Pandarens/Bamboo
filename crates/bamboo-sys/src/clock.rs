//! Часы для отметок сэмплов.

use bamboo_core::SampleTime;
use windows_sys::Win32::System::SystemInformation::GetTickCount64;
use windows_sys::Win32::System::WindowsProgramming::QueryUnbiasedInterruptTime;

/// Монотонное время в миллисекундах от загрузки системы.
///
/// Настенные часы для интервалов не годятся: они прыгают при синхронизации
/// времени и при выходе из сна, а на прыжке назад загрузка процессора
/// вычисляется как деление на отрицательный интервал.
pub fn monotonic_ms() -> u64 {
    unsafe { GetTickCount64() }
}

/// Отметка «сейчас» для сэмпла: монотонная и настенная шкалы вместе.
pub fn now() -> SampleTime {
    SampleTime::new(monotonic_ms(), SampleTime::wall_clock_now())
}

/// Время работы без учёта сна, миллисекунды.
///
/// Нужны именно такие часы, чтобы измерять подвисания напрямую. Приём
/// прост: попросить поспать секунду и посмотреть, сколько прошло на самом
/// деле. Проспали три — значит система две секунды не отвечала, и это
/// не вывод из косвенных признаков, а само подвисание, измеренное
/// секундомером.
///
/// Обычные часы для этого не годятся: ночь в спящем режиме они посчитают
/// восьмичасовым подвисанием. `QueryUnbiasedInterruptTime` время сна
/// не учитывает — на то он и «несмещённый».
///
/// Единицы возвращаются по 100 нс, отсюда деление на десять тысяч.
/// Разрешение у счётчика — примерно шаг системного таймера, 15 мс,
/// и для подвисаний в сотни миллисекунд этого с запасом.
pub fn unbiased_ms() -> u64 {
    let mut units: u64 = 0;
    // SAFETY: вызов пишет одно число по переданному указателю.
    // Возвращаемое значение — признак успеха; при неудаче остаётся ноль,
    // и разность двух нулей даст нулевой простой, а не выдуманный.
    unsafe { QueryUnbiasedInterruptTime(&mut units) };
    units / 10_000
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Часы без учёта сна идут вперёд и не отстают от запрошенного сна.
    ///
    /// Проверяем то самое свойство, ради которого они заведены: если
    /// поспать 120 мс, эти часы обязаны показать не меньше — иначе
    /// вычитать из них простой было бы нельзя.
    #[test]
    fn unbiased_clock_measures_the_sleep_it_was_asked_for() {
        let before = unbiased_ms();
        std::thread::sleep(std::time::Duration::from_millis(120));
        let slept = unbiased_ms().saturating_sub(before);
        assert!(slept >= 100, "часы показали всего {slept} мс за 120 мс сна");
        // Верхняя граница просторная: на занятой машине поток могут
        // и подержать. Ловим не точность, а сломанные единицы измерения —
        // счётчик отдаёт сотни наносекунд, и забытое деление дало бы здесь
        // больше миллиона.
        assert!(slept < 10_000, "часы показали {slept} мс — единицы поехали");
    }

    #[test]
    fn monotonic_clock_moves_forward() {
        let first = monotonic_ms();
        std::thread::sleep(std::time::Duration::from_millis(50));
        let second = monotonic_ms();
        assert!(second >= first);
        assert!(second - first >= 30, "прошло всего {} мс", second - first);
    }

    #[test]
    fn wall_clock_is_in_a_plausible_range() {
        // Больше 2020 года и меньше 2100-го: ловим перепутанные единицы.
        let unix_ms = now().unix_ms;
        assert!(unix_ms > 1_577_836_800_000);
        assert!(unix_ms < 4_102_444_800_000);
    }
}
