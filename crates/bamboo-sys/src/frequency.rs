//! На какой доле номинальной частоты работает процессор.
//!
//! Нужно ради причины подвисаний, которую иначе не опознать: сброс частоты.
//! Процессор при перегреве или упёршись в предел питания снижает частоту
//! вдвое и втрое, оставаясь «занятым на сто процентов». Снаружи это
//! выглядит как загруженный процессор, а на деле машина работает
//! в полсилы — и никакая проверка загрузки этого не покажет.
//!
//! Счётчик отдаёт проценты от номинальной частоты и **законно** бывает
//! больше ста: это ускорение, штатная работа процессора под нагрузкой.
//!
//! Само по себе низкое значение ничего не значит и кричать о нём нельзя:
//! на простое процессор снижает частоту нарочно, ради экономии, и это
//! здоровое поведение. Признаком беды низкая частота становится, только
//! когда процессор при этом загружен, то есть его просят работать,
//! а он не может.

use bamboo_core::Result;

use crate::pdh::Counter;

/// Набор «Processor Information», а не «Processor»: старый набор не знает
/// про группы процессоров и на машинах с числом ядер больше 64 врёт.
const PERFORMANCE_COUNTER: &str = r"\Processor Information(_Total)\% Processor Performance";

/// Открытый счётчик доли номинальной частоты.
pub struct FrequencyCounter(Counter);

impl FrequencyCounter {
    pub fn open() -> Result<FrequencyCounter> {
        Counter::open(
            PERFORMANCE_COUNTER,
            "счётчик частоты процессора в этой системе недоступен",
        )
        .map(FrequencyCounter)
    }

    /// Доля номинальной частоты: 1.0 — номинал, 0.5 — половина,
    /// больше единицы — ускорение под нагрузкой.
    ///
    /// Ноль на первом замере: промежутка, за который считать, ещё нет.
    /// Вызывающий обязан отличать этот ноль от настоящего сброса частоты,
    /// и отличает он его тем же, чем настоящий сброс от простоя, —
    /// загрузкой процессора.
    pub fn read(&mut self) -> Result<f64> {
        self.0.read().map(|percent| percent / 100.0)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_counter_reports_a_believable_share_of_nominal() {
        let mut counter = FrequencyCounter::open().expect("счётчик частоты обязан открываться");
        assert_eq!(counter.read().unwrap(), 0.0, "первый замер — всегда ноль");

        std::thread::sleep(std::time::Duration::from_millis(300));
        let share = counter.read().unwrap();
        // Верхнюю границу не ставим на единице намеренно: ускорение —
        // это штатная работа, и процессор законно идёт выше номинала.
        // Ловим перепутанные единицы: если бы проценты забыли поделить,
        // здесь оказалась бы сотня.
        assert!(share < 10.0, "доля номинала вышла нелепой: {share}");
    }
}
